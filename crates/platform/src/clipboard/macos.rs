#![allow(unsafe_code)]

use std::path::{Path, PathBuf};
use std::{fs, io};

use image::ImageFormat;
use objc2::rc::autoreleasepool;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardTypeFileURL, NSPasteboardTypeHTML,
    NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF, NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSString, NSURL};
use unikvm_core::clipboard::{Content, MAX_FILES, MAX_HTML_BYTES, MAX_TEXT_BYTES};

use super::{Snapshot, WriteOutcome, imaging};

const TRANSIENT: &str = "org.nspasteboard.TransientType";
const IMPORTED: &str = "org.unikvm.received-clipboard";
const JPEG: &str = "public.jpeg";
const MAX_PASTEBOARD_ITEMS: usize = 16;
const SKIP_TYPES: &[&str] = &[
    TRANSIENT,
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "com.apple.is-remote-clipboard",
];
const LEGACY_FILE_LIST: &str = "NSFilenamesPboardType";

pub struct Clipboard {
    board: objc2::rc::Retained<NSPasteboard>,
}

impl Clipboard {
    pub fn new() -> io::Result<Self> {
        Ok(Self {
            board: autoreleasepool(|_| NSPasteboard::generalPasteboard()),
        })
    }

    pub fn available(&self) -> bool {
        !crate::input::macos_session::capture_unavailable()
            && !crate::input::macos_capture::secure_input()
    }

    pub fn sequence(&self) -> io::Result<u64> {
        autoreleasepool(|_| Ok(self.board.changeCount() as u64))
    }

    pub fn read(&self, previous: u64) -> io::Result<Option<Snapshot>> {
        autoreleasepool(|_| {
            let sequence = self.sequence()?;
            if sequence == previous {
                return Ok(None);
            }
            // SAFETY: AppKit initializes these immutable exported type names.
            let (text_type, html_type, file_type, png_type, tiff_type) = unsafe {
                (
                    NSPasteboardTypeString,
                    NSPasteboardTypeHTML,
                    NSPasteboardTypeFileURL,
                    NSPasteboardTypePNG,
                    NSPasteboardTypeTIFF,
                )
            };
            let types = self.board.types();
            let imported = types
                .as_ref()
                .is_some_and(|types| types.containsObject(&NSString::from_str(IMPORTED)));
            let eligible = !imported
                && types.as_ref().is_some_and(|types| {
                    !SKIP_TYPES
                        .iter()
                        .any(|name| types.containsObject(&NSString::from_str(name)))
                });
            let content = eligible.then(|| {
                let items = self.board.pasteboardItems()?;
                let jpeg = NSString::from_str(JPEG);
                let formats = [
                    (png_type, ImageFormat::Png),
                    (tiff_type, ImageFormat::Tiff),
                    (&*jpeg, ImageFormat::Jpeg),
                ];
                // Use a single explicit raster representation. Auxiliary items
                // and a plain URL or caption do not take precedence over pixels.
                for index in 0..items.len().min(MAX_PASTEBOARD_ITEMS) {
                    let item = items.objectAtIndex(index);
                    let types = item.types();
                    let png = formats
                        .iter()
                        .filter(|(kind, _)| types.containsObject(kind))
                        .find_map(|(kind, format)| {
                            let data = read_item(&item, kind, imaging::MAX_NATIVE_BYTES)?;
                            imaging::normalize(&data, *format)
                        });
                    if let Some(png) = png {
                        return Some(Content::Png(png));
                    }
                }
                let types = types.as_ref()?;
                if types.containsObject(file_type) {
                    return file_paths(&items, file_type).map(Content::Files);
                }
                if types.containsObject(&NSString::from_str(LEGACY_FILE_LIST)) {
                    return None;
                }
                if items.len() != 1 {
                    return None;
                }
                let item = items.firstObject()?;
                let plain = item.dataForType(text_type)?;
                let html = item.dataForType(html_type);
                if plain.len() > MAX_TEXT_BYTES
                    || html
                        .as_ref()
                        .is_some_and(|html| html.len() > MAX_HTML_BYTES)
                {
                    return Some(Content::TooLarge);
                }
                let plain = String::from_utf8(plain.to_vec()).ok()?;
                let html = html.and_then(|data| String::from_utf8(data.to_vec()).ok());
                Some(Content::Text { plain, html })
            });
            // The type list and the contents must belong to the same item generation.
            Ok((self.sequence()? == sequence).then_some(Snapshot {
                sequence,
                content: content.flatten(),
                imported,
            }))
        })
    }

    pub fn write(&self, expected: u64, content: &Content) -> io::Result<WriteOutcome> {
        autoreleasepool(|_| {
            if let Content::Files(paths) = content {
                return self.write_files(expected, paths);
            }
            let item = NSPasteboardItem::new();
            // SAFETY: AppKit initializes this immutable exported type name.
            let (text_type, html_type, png_type, tiff_type) = unsafe {
                (
                    NSPasteboardTypeString,
                    NSPasteboardTypeHTML,
                    NSPasteboardTypePNG,
                    NSPasteboardTypeTIFF,
                )
            };
            let set = |kind, bytes: &[u8]| item.setData_forType(&NSData::with_bytes(bytes), kind);
            let prepared = match content {
                Content::Text { plain, html } => {
                    if let Some(html) = html {
                        let _ = set(html_type, html.as_bytes());
                    }
                    set(text_type, plain.as_bytes())
                }
                Content::Png(png) => {
                    let Some(pixels) = imaging::decode(png, ImageFormat::Png) else {
                        return Ok(WriteOutcome::Unsupported);
                    };
                    let Some(png) = imaging::to_png(&pixels) else {
                        return Ok(WriteOutcome::Unsupported);
                    };
                    if let Some(tiff) = imaging::to_tiff(&pixels) {
                        let _ = set(tiff_type, &tiff);
                    }
                    set(png_type, &png)
                }
                Content::Files(_) | Content::TooLarge => return Ok(WriteOutcome::Unsupported),
            };
            if !prepared || !mark_imported(&item) {
                return Err(io::Error::other("could not prepare Mac pasteboard data"));
            }
            let item = ProtocolObject::<dyn NSPasteboardWriting>::from_retained(item);
            let items = NSArray::from_retained_slice(&[item]);
            if self.sequence()? != expected {
                return Ok(WriteOutcome::Changed);
            }
            let sequence = self.board.clearContents() as u64;
            if !self.board.writeObjects(&items) {
                return Err(io::Error::other("could not write Mac pasteboard data"));
            }
            Ok(WriteOutcome::Applied(sequence))
        })
    }

    fn write_files(&self, expected: u64, paths: &[PathBuf]) -> io::Result<WriteOutcome> {
        let mut items = Vec::with_capacity(paths.len());
        // SAFETY: AppKit initializes this immutable type name.
        let kind = unsafe { NSPasteboardTypeFileURL };
        for path in paths {
            let path = path
                .to_str()
                .ok_or_else(|| io::Error::from(io::ErrorKind::InvalidInput))?;
            let url = NSURL::fileURLWithPath_isDirectory(&NSString::from_str(path), false);
            let url = url
                .absoluteString()
                .ok_or_else(|| io::Error::from(io::ErrorKind::InvalidInput))?;
            let item = NSPasteboardItem::new();
            if !item.setString_forType(&url, kind) || !mark_imported(&item) {
                return Err(io::Error::other("could not prepare Mac file reference"));
            }
            items.push(ProtocolObject::<dyn NSPasteboardWriting>::from_retained(
                item,
            ));
        }
        if self.sequence()? != expected {
            return Ok(WriteOutcome::Changed);
        }
        self.board.clearContents();
        if !self
            .board
            .writeObjects(&NSArray::from_retained_slice(&items))
        {
            return Err(io::Error::other("could not write Mac file references"));
        }
        Ok(WriteOutcome::Applied(self.sequence()?))
    }

    pub fn imported_files(&self) -> io::Result<Option<Vec<PathBuf>>> {
        autoreleasepool(|_| {
            let imported = self
                .board
                .types()
                .is_some_and(|types| types.containsObject(&NSString::from_str(IMPORTED)));
            // SAFETY: AppKit initializes the immutable pasteboard type.
            let kind = unsafe { NSPasteboardTypeFileURL };
            Ok(if imported {
                self.board
                    .pasteboardItems()
                    .and_then(|items| file_paths(&items, kind))
            } else {
                None
            })
        })
    }
}

pub fn staging_directory() -> io::Result<PathBuf> {
    crate::local::Endpoint::for_current_user()?
        .clipboard_directory()?
        .canonicalize()
}

fn file_paths(items: &NSArray<NSPasteboardItem>, kind: &NSString) -> Option<Vec<PathBuf>> {
    if !(1..=MAX_FILES).contains(&items.len()) {
        return None;
    }
    let paths = (0..items.len())
        .filter_map(|index| {
            let item = items.objectAtIndex(index);
            item.types().containsObject(kind).then_some(item)
        })
        .map(|item| {
            let text = item.stringForType(kind)?;
            if text.len() > 32_768 {
                return None;
            }
            let url = NSURL::URLWithString(&text)?;
            if !url.isFileURL()
                || url.host().is_some_and(|host| {
                    let host = host.to_string();
                    !host.is_empty() && host != "localhost"
                })
            {
                return None;
            }
            let path = PathBuf::from(url.path()?.to_string());
            path.is_absolute().then_some(path)
        })
        .collect::<Option<Vec<_>>>()?;
    (!paths.is_empty()).then_some(paths)
}

fn mark_imported(item: &NSPasteboardItem) -> bool {
    let empty = NSData::with_bytes(&[]);
    item.setData_forType(&empty, &NSString::from_str(TRANSIENT))
        && item.setData_forType(&empty, &NSString::from_str(IMPORTED))
}

pub fn open_source(path: &Path) -> io::Result<fs::File> {
    use rustix::fs::{Mode, OFlags, open};

    if !path.is_absolute() {
        return Err(io::ErrorKind::InvalidInput.into());
    }
    let file: fs::File = open(
        path,
        OFlags::RDONLY | OFlags::CLOEXEC | OFlags::NOFOLLOW | OFlags::NONBLOCK,
        Mode::empty(),
    )?
    .into();
    if !file.metadata()?.is_file() {
        return Err(io::ErrorKind::InvalidInput.into());
    }
    Ok(file)
}

fn read_item(item: &NSPasteboardItem, kind: &NSString, limit: usize) -> Option<Vec<u8>> {
    let data = item.dataForType(kind)?;
    (data.len() <= limit).then(|| data.to_vec())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[ignore = "requires a logged-in macOS desktop"]
    fn native_text_and_html_round_trip_uses_a_transient_marker_on_received_data() {
        autoreleasepool(|_| {
            let clipboard = Clipboard {
                board: NSPasteboard::pasteboardWithUniqueName(),
            };
            let initial = clipboard.sequence().unwrap();
            let text = "日本語\n🧪";
            let html = "<strong>日本語</strong><br>🧪";
            clipboard.board.clearContents();
            // SAFETY: AppKit initializes the immutable exported type name.
            let (kind, rich) = unsafe { (NSPasteboardTypeString, NSPasteboardTypeHTML) };
            assert!(
                clipboard
                    .board
                    .setString_forType(&NSString::from_str(text), kind)
            );
            assert!(
                clipboard
                    .board
                    .setData_forType(Some(&NSData::with_bytes(html.as_bytes())), rich)
            );
            let snapshot = clipboard.read(initial).unwrap().unwrap();
            let content = snapshot.content.unwrap();
            assert!(matches!(&content, Content::Text { plain, html: rich }
                if plain == text && rich.as_deref() == Some(html)));
            let WriteOutcome::Applied(_) = clipboard.write(snapshot.sequence, &content).unwrap()
            else {
                panic!("private pasteboard changed unexpectedly");
            };
            let snapshot = clipboard.read(snapshot.sequence).unwrap().unwrap();
            assert!(snapshot.content.is_none());
            assert!(clipboard.board.stringForType(kind).unwrap().to_string() == text);
            assert!(clipboard.board.dataForType(rich).unwrap().to_vec() == html.as_bytes());
            clipboard.board.clearContents();
        });
    }

    #[test]
    #[ignore = "requires a logged-in macOS desktop"]
    fn native_image_with_a_file_reference_is_imported_without_echo() {
        autoreleasepool(|_| {
            let clipboard = Clipboard {
                board: NSPasteboard::pasteboardWithUniqueName(),
            };
            let source = image::RgbaImage::from_pixel(2, 3, image::Rgba([20, 80, 120, 64]));
            // SAFETY: AppKit initializes these immutable exported type names.
            let (png_type, tiff_type, text_type, file_type) = unsafe {
                (
                    NSPasteboardTypePNG,
                    NSPasteboardTypeTIFF,
                    NSPasteboardTypeString,
                    NSPasteboardTypeFileURL,
                )
            };
            let initial = clipboard.sequence().unwrap();
            clipboard.board.clearContents();
            let tiff = imaging::to_tiff(&source).unwrap();
            let copied = NSPasteboardItem::new();
            assert!(copied.setString_forType(&NSString::from_str("Image caption"), text_type));
            assert!(copied.setData_forType(&NSData::with_bytes(&tiff), tiff_type));
            let auxiliary = NSPasteboardItem::new();
            assert!(auxiliary.setString_forType(
                &NSString::from_str("file:///tmp/unikvm-unused-image.jpg"),
                file_type,
            ));
            let items = NSArray::from_retained_slice(&[
                ProtocolObject::<dyn NSPasteboardWriting>::from_retained(auxiliary),
                ProtocolObject::<dyn NSPasteboardWriting>::from_retained(copied),
            ]);
            assert!(clipboard.board.writeObjects(&items));
            let snapshot = clipboard.read(initial).unwrap().unwrap();
            let Some(content @ Content::Png(_)) = snapshot.content else {
                panic!("private pasteboard did not expose an image");
            };
            assert!(matches!(
                clipboard.write(snapshot.sequence, &content).unwrap(),
                WriteOutcome::Applied(_)
            ));
            assert!(
                clipboard
                    .read(snapshot.sequence)
                    .unwrap()
                    .unwrap()
                    .content
                    .is_none()
            );
            assert!(clipboard.board.dataForType(tiff_type).is_some());
            let png = clipboard.board.dataForType(png_type).unwrap().to_vec();
            assert_eq!(imaging::decode(&png, ImageFormat::Png).unwrap(), source);
            clipboard.board.clearContents();
        });
    }

    #[test]
    #[ignore = "requires a logged-in macOS desktop"]
    fn native_file_reference_round_trips_without_echo() {
        autoreleasepool(|_| {
            let clipboard = Clipboard {
                board: NSPasteboard::pasteboardWithUniqueName(),
            };
            let initial = clipboard.sequence().unwrap();
            let item = NSPasteboardItem::new();
            // SAFETY: AppKit initializes these immutable exported type names.
            let (file_type, text_type) =
                unsafe { (NSPasteboardTypeFileURL, NSPasteboardTypeString) };
            assert!(item.setString_forType(
                &NSString::from_str("file:///tmp/unikvm-unused-image.jpg"),
                file_type,
            ));
            assert!(
                item.setString_forType(&NSString::from_str("unikvm-unused-image.jpg"), text_type,)
            );
            let items = NSArray::from_retained_slice(&[
                ProtocolObject::<dyn NSPasteboardWriting>::from_retained(item),
            ]);
            clipboard.board.clearContents();
            assert!(clipboard.board.writeObjects(&items));
            let snapshot = clipboard.read(initial).unwrap().unwrap();
            let content = snapshot.content.unwrap();
            assert!(
                matches!(&content, Content::Files(paths) if paths == &[PathBuf::from("/tmp/unikvm-unused-image.jpg")])
            );
            assert!(matches!(
                clipboard.write(snapshot.sequence, &content).unwrap(),
                WriteOutcome::Applied(_)
            ));
            assert!(clipboard.read(snapshot.sequence).unwrap().unwrap().imported);
            assert!(clipboard.board.stringForType(file_type).is_some());
            clipboard.board.clearContents();
        });
    }
}
